// Command genregex generates lib/std/src/regex/unicode.navi: the Unicode
// tables of std::regex (general categories, scripts, the properties behind
// \w, \s and \p{Alphabetic}, and simple case folding), taken from Go's
// unicode package.
//
//	go run ./tools/genregex > lib/std/src/regex/unicode.navi
package main

import (
	"fmt"
	"os"
	"sort"
	"strings"
	"unicode"
)

var categories = []string{
	"Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No",
	"Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po", "Sm", "Sc", "Sk", "So",
	"Zs", "Zl", "Zp", "Cc", "Cf", "Cs", "Co",
}

var props = []string{"White_Space", "Join_Control", "Other_Alphabetic", "Other_Lowercase", "Other_Uppercase"}

type rng struct{ lo, hi, idx uint32 }

func ranges(t *unicode.RangeTable, idx uint32) []rng {
	var out []rng
	add := func(lo, hi, stride uint32) {
		if stride == 1 {
			out = append(out, rng{lo, hi, idx})
			return
		}
		for c := lo; c <= hi; c += stride {
			out = append(out, rng{c, c, idx})
		}
	}
	for _, r := range t.R16 {
		add(uint32(r.Lo), uint32(r.Hi), uint32(r.Stride))
	}
	for _, r := range t.R32 {
		add(r.Lo, r.Hi, r.Stride)
	}
	return out
}

// merged sorts ranges and joins adjacent ones with the same index.
func merged(rs []rng) []rng {
	sort.Slice(rs, func(i, j int) bool { return rs[i].lo < rs[j].lo })
	var out []rng
	for _, r := range rs {
		if n := len(out); n > 0 && out[n-1].idx == r.idx && out[n-1].hi+1 == r.lo {
			out[n-1].hi = r.hi
			continue
		}
		out = append(out, r)
	}
	return out
}

func table(w *strings.Builder, name, doc string, rs []rng) {
	fmt.Fprintf(w, "%s\npub static %s: [u32; %d] = [", doc, name, 2*len(rs))
	for i, r := range rs {
		if i%6 == 0 {
			w.WriteString("\n   ")
		}
		fmt.Fprintf(w, " 0x%x, 0x%x,", r.lo|r.idx<<21, r.hi)
	}
	w.WriteString("\n];\n\n")
}

func names(w *strings.Builder, name string, ns []string) {
	fmt.Fprintf(w, "pub static %s: [&str; %d] = [", name, len(ns))
	for i, n := range ns {
		if i%8 == 0 {
			w.WriteString("\n   ")
		}
		fmt.Fprintf(w, " %q,", n)
	}
	w.WriteString("\n];\n\n")
}

func main() {
	var w strings.Builder
	fmt.Fprintf(&w, "//! Unicode %s tables for std::regex. Generated by tools/genregex from Go's\n//! unicode package; do not edit.\n//!\n", unicode.Version)
	w.WriteString("//! A range table holds pairs (lo | index << 21, hi), sorted by lo; the index\n//! selects the category, script or property in the matching name list.\n\n")

	names(&w, "CATEGORY_NAMES", categories)
	var rs []rng
	for i, c := range categories {
		rs = append(rs, ranges(unicode.Categories[c], uint32(i))...)
	}
	table(&w, "CATEGORIES", "/// General categories (index into CATEGORY_NAMES).", merged(rs))

	var scripts []string
	for s := range unicode.Scripts {
		scripts = append(scripts, s)
	}
	sort.Strings(scripts)
	names(&w, "SCRIPT_NAMES", scripts)
	rs = nil
	for i, s := range scripts {
		rs = append(rs, ranges(unicode.Scripts[s], uint32(i))...)
	}
	table(&w, "SCRIPTS", "/// Scripts (index into SCRIPT_NAMES).", merged(rs))

	names(&w, "PROP_NAMES", props)
	rs = nil
	for i, p := range props {
		rs = append(rs, ranges(unicode.Properties[p], uint32(i))...)
	}
	sort.SliceStable(rs, func(i, j int) bool { return rs[i].lo < rs[j].lo })
	table(&w, "PROPS", "/// Binary properties (index into PROP_NAMES); ranges of different\n/// properties may overlap.", rs)

	// Simple case folding: c maps to the next character of its orbit
	// (unicode.SimpleFold), stored as runs (lo, hi, stride, delta).
	type run struct{ lo, hi, stride, delta int32 }
	var runs []run
	for c := rune(0); c <= unicode.MaxRune; c++ {
		f := unicode.SimpleFold(c)
		if f == c {
			continue
		}
		d := int32(f - c)
		// Extend one of the last two runs (upper and lower case letters
		// often alternate, so two runs may interleave).
		extended := false
		for k := len(runs) - 1; k >= 0 && k >= len(runs)-2 && !extended; k-- {
			r := &runs[k]
			gap := int32(c) - r.hi
			if r.delta != d {
				continue
			}
			if r.lo == r.hi && (gap == 1 || gap == 2) {
				r.stride = gap
				r.hi = int32(c)
				extended = true
			} else if r.lo != r.hi && gap == r.stride {
				r.hi = int32(c)
				extended = true
			}
		}
		if !extended {
			runs = append(runs, run{int32(c), int32(c), 1, d})
		}
	}
	fmt.Fprintf(&w, "/// Simple case folding: for c in lo..=hi stepping by stride, the next\n/// character of c's case orbit is c + delta. Entries (lo, hi, stride, delta).\npub static FOLD: [i32; %d] = [", 4*len(runs))
	for i, r := range runs {
		if i%4 == 0 {
			w.WriteString("\n   ")
		}
		fmt.Fprintf(&w, " 0x%x, 0x%x, %d, %d,", r.lo, r.hi, r.stride, r.delta)
	}
	w.WriteString("\n];\n")
	os.Stdout.WriteString(w.String())
}
