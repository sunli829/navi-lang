def limbs(x, n):
    return [(x >> (64 * i)) & 0xffffffffffffffff for i in range(n)]


def arr(x, n):
    return '[' + ', '.join(f'{v:#x}' for v in limbs(x, n)) + ']'


def be_bytes(x, n):
    return '[' + ', '.join(f'{b:#04x}' for b in x.to_bytes(n, 'big')) + ']'


# The comment of a field function, and its declaration in assembly on the
# curve's asm architectures (nistec_<key>_<arch>.s, tools/genp256asm.py),
# the code that follows for the others.
def asm_or(w, key, c, sig, doc):
    asm = c.get('asm', [])
    if not asm:
        w(f'// {doc}')
        return
    arches = ', '.join(f'target_arch = "{a}"' for a in asm)
    w(f'// {doc} In assembly on {", ".join(asm)} (nistec_{key}_<arch>.s).')
    w(f'#[cfg(any({arches}))]')
    w('#[asm]')
    w(f'{sig};')
    w('')
    w(f'#[cfg(not(any({arches})))]')


def gen(key, c):
    p, n = c['p'], c['limbs']
    size = (p.bit_length() + 7) // 8
    R = 1 << (64 * n)
    m0inv = (-pow(p, -1, 1 << 64)) % (1 << 64)
    out = []
    w = out.append
    w(f'//! Generated by tools/gennistec.py (do not edit): {c["name"]} for crypto::ec,')
    w('//! as Go\'s crypto/internal/fips140/nistec. Field elements are')
    w(f'//! [u64; {n}] in Montgomery form (little-endian limbs); points are')
    w('//! Jacobian (x = X/Z^2, y = Y/Z^3), the identity Z = 0, with the formulas')
    w('//! of Go\'s P-256 assembly (a = -3). Scalar multiplication reads signed')
    w('//! 5-bit windows\' table in constant time (Go\'s p256ScalarMult); the')
    w('//! generator\'s multiples per 4-bit window are an affine table built on')
    w('//! first use, added by mixed additions.')
    w('')
    w('use crate::sync::LazyLock;')
    w('')
    w(f'type Fe = [u64; {n}];')
    w('')
    w(f'const P: Fe = {arr(p, n)};')
    w(f'const ZERO: Fe = {arr(0, n)};')
    w(f'// 1, R^2, b, the generator (Montgomery form).')
    w(f'const ONE: Fe = {arr(R % p, n)};')
    w(f'const RR: Fe = {arr(R * R % p, n)};')
    w(f'const B: Fe = {arr(c["b"] * R % p, n)};')
    w(f'const GX: Fe = {arr(c["gx"] * R % p, n)};')
    w(f'const GY: Fe = {arr(c["gy"] * R % p, n)};')
    w(f'const SIZE: usize = {size};')
    w(f'const LIMBS: usize = {n};')
    # The top 5-bit window of the scalars below the order (Go's p256: 254).
    nb = c['n'].bit_length()
    top = max(i for i in range(nb - 1) if i % 5 == 4)
    w(f'const TOP_WINDOW: usize = {top};')
    w(f'// p - 2 (inversion) and (p + 1) / 4 (square roots), big-endian.')
    w(f'const P_MINUS_2: [u8; {size}] = {be_bytes(p - 2, size)};')
    w(f'const SQRT_EXP: [u8; {size}] = {be_bytes((p + 1) // 4, size)};')
    w('')
    w('// The carries are bools: carrying_add / borrowing_sub chains are adcs / sbcs.')
    w('#[inline(always)]')
    w('fn adc(a: u64, b: u64, c: bool) -> (u64, bool) { a.carrying_add(b, c) }')
    w('')
    w('#[inline(always)]')
    w('fn sbb(a: u64, b: u64, borrow: bool) -> (u64, bool) { a.borrowing_sub(b, borrow) }')
    w('')
    w('// a * b + c + d (fits 128 bits): (lo, hi).')
    w('#[inline(always)]')
    w('fn mac(a: u64, b: u64, c: u64, d: u64) -> (u64, u64) {')
    w('    let (lo, hi) = a.widening_mul(b);')
    w('    let (s, c1) = lo.carrying_add(c, false);')
    w('    let (h, _) = hi.carrying_add(0, c1);')
    w('    let (s2, c2) = s.carrying_add(d, false);')
    w('    let (h2, _) = h.carrying_add(0, c2);')
    w('    (s2, h2)')
    w('}')
    w('')
    # Montgomery multiplication (CIOS), unrolled.
    asm_or(w, key, c, 'fn fe_mul(a: &Fe, b: &Fe) -> Fe', 'a * b / R mod p (CIOS, unrolled).')
    w('fn fe_mul(a: &Fe, b: &Fe) -> Fe {')
    for i in range(n + 2):
        w(f'    let mut t{i} = 0u64;')
    w('    let mut c: u64;')
    for i in range(n):
        w(f'    let bi = b[{i}];')
        w('    c = 0;')
        for j in range(n):
            w(f'    let (x, y) = mac(a[{j}], bi, t{j}, c); t{j} = x; c = y;')
        w(f'    let (x, y) = adc(t{n}, c, false); t{n} = x; t{n + 1} = y as u64;')
        if m0inv == 1:
            w('    let q = t0;')
        else:
            w(f'    let q = t0.wrapping_mul({m0inv:#x});')
        w(f'    let (_, y) = mac(q, P[0], t0, 0); c = y;')
        for j in range(1, n):
            w(f'    let (x, y) = mac(q, P[{j}], t{j}, c); t{j - 1} = x; c = y;')
        w(f'    let (x, y) = adc(t{n}, c, false); t{n - 1} = x; t{n} = t{n + 1}.wrapping_add(y as u64);')
    w('    // t < 2p: subtract p unless t < p.')
    w('    let (r0, w0) = sbb(t0, P[0], false);')
    for j in range(1, n):
        w(f'    let (r{j}, w{j}) = sbb(t{j}, P[{j}], w{j - 1});')
    w(f'    let (_, bb) = sbb(t{n}, 0, w{n - 1});')
    w('    let mask = 0u64.wrapping_sub(bb as u64);')
    w('    [' + ', '.join(f'(t{j} & mask) | (r{j} & !mask)' for j in range(n)) + ']')
    w('}')
    w('')
    asm_or(w, key, c, 'fn fe_sqr(a: &Fe) -> Fe', 'a * a / R mod p.')
    w('fn fe_sqr(a: &Fe) -> Fe { fe_mul(a, a) }')
    w('')
    asm_or(w, key, c, 'fn fe_add(a: &Fe, b: &Fe) -> Fe', 'a + b mod p.')
    w('fn fe_add(a: &Fe, b: &Fe) -> Fe {')
    w('    let (s0, c0) = adc(a[0], b[0], false);')
    for j in range(1, n):
        w(f'    let (s{j}, c{j}) = adc(a[{j}], b[{j}], c{j - 1});')
    w('    let (d0, w0) = sbb(s0, P[0], false);')
    for j in range(1, n):
        w(f'    let (d{j}, w{j}) = sbb(s{j}, P[{j}], w{j - 1});')
    w(f'    // Keep the sum when it is below p (no carry, a borrow).')
    w(f'    let (_, keep) = sbb(c{n - 1} as u64, 0, w{n - 1});')
    w('    let mask = 0u64.wrapping_sub(keep as u64);')
    w('    [' + ', '.join(f'(s{j} & mask) | (d{j} & !mask)' for j in range(n)) + ']')
    w('}')
    w('')
    asm_or(w, key, c, 'fn fe_sub(a: &Fe, b: &Fe) -> Fe', 'a - b mod p.')
    w('fn fe_sub(a: &Fe, b: &Fe) -> Fe {')
    w('    let (d0, w0) = sbb(a[0], b[0], false);')
    for j in range(1, n):
        w(f'    let (d{j}, w{j}) = sbb(a[{j}], b[{j}], w{j - 1});')
    w(f'    // Add p back on a borrow.')
    w(f'    let mask = 0u64.wrapping_sub(w{n - 1} as u64);')
    w('    let (r0, c0) = adc(d0, P[0] & mask, false);')
    for j in range(1, n):
        w(f'    let (r{j}, c{j}) = adc(d{j}, P[{j}] & mask, c{j - 1});')
    w(f'    let _ = c{n - 1};')
    w('    [' + ', '.join(f'r{j}' for j in range(n)) + ']')
    w('}')
    w('')
    w('// c ? a : b (c is 0 or 1), in constant time.')
    w('fn fe_select(c: u64, a: &Fe, b: &Fe) -> Fe {')
    w('    let mask = 0u64.wrapping_sub(c);')
    w('    [' + ', '.join(f'(a[{j}] & mask) | (b[{j}] & !mask)' for j in range(n)) + ']')
    w('}')
    w('')
    w('// 1 if a is zero, else 0.')
    w('fn fe_is_zero(a: &Fe) -> u64 {')
    w('    let x = ' + ' | '.join(f'a[{j}]' for j in range(n)) + ';')
    w('    ((x | x.wrapping_neg()) >> 63) ^ 1')
    w('}')
    w('')
    w('fn fe_eq(a: &Fe, b: &Fe) -> bool { fe_is_zero(&fe_sub(a, b)) == 1 }')
    w('')
    w('// a^e, e big-endian (public: the steps depend on its bits).')
    w('fn fe_pow(a: &Fe, e: &[u8]) -> Fe {')
    w('    let mut r = ONE;')
    w('    for byte in e.iter() {')
    w('        let mut k = 8;')
    w('        while k > 0 {')
    w('            k -= 1;')
    w('            r = fe_sqr(&r);')
    w('            if ((*byte >> k as u8) & 1) != 0 { r = fe_mul(&r, a); }')
    w('        }')
    w('    }')
    w('    r')
    w('}')
    w('')
    w('fn fe_inv(a: &Fe) -> Fe { fe_pow(a, &P_MINUS_2) }')
    w('')
    w('// The element of big-endian bytes (SIZE of them), if below p.')
    w('fn fe_from_be(b: &[u8]) -> Option<Fe> {')
    w('    if b.len() != SIZE { return None; }')
    w('    let mut x: Fe = ZERO;')
    w('    let mut i = 0;')
    w('    while i < SIZE {')
    w('        let k = SIZE - 1 - i;')
    w('        x[k / 8] = x[k / 8] | ((b[i] as u64) << (8 * (k % 8)) as u64);')
    w('        i += 1;')
    w('    }')
    w('    let (_, w0) = sbb(x[0], P[0], false);')
    for j in range(1, n):
        w(f'    let (_, w{j}) = sbb(x[{j}], P[{j}], w{j - 1});')
    w(f'    if !w{n - 1} {{ return None; }}')
    w('    Some(fe_mul(&x, &RR))')
    w('}')
    w('')
    w('// Big-endian bytes (SIZE) of an element.')
    w('fn fe_to_be(a: &Fe) -> Vec<u8> {')
    w('    let mut one: Fe = ZERO;')
    w('    one[0] = 1;')
    w('    let x = fe_mul(a, &one);')
    w('    let mut out: Vec<u8> = Vec::with_capacity(SIZE);')
    w('    let mut k = SIZE;')
    w('    while k > 0 {')
    w('        k -= 1;')
    w('        out.push((x[k / 8] >> (8 * (k % 8)) as u64) as u8);')
    w('    }')
    w('    out')
    w('}')
    w('')
    w('#[derive(Clone)]')
    w('struct Point {')
    w('    x: Fe,')
    w('    y: Fe,')
    w('    z: Fe,')
    w('}')
    w('')
    w('fn identity() -> Point { Point { x: ZERO, y: ONE, z: ZERO } }')
    w('')
    w('fn generator() -> Point { Point { x: GX, y: GY, z: ONE } }')
    w('')
    w("// The point formulas are Go's for P-256 (p256_asm_*.s: Jacobian")
    w('// coordinates, x = X/Z^2, y = Y/Z^3, a = -3; the identity has Z = 0).')
    w('')
    w('// p + p (dbl-2001-b: 4M + 4S); the identity doubles to itself.')
    w('fn double(p: &Point) -> Point {')
    w('    let delta = fe_sqr(&p.z);')
    w('    let gamma = fe_sqr(&p.y);')
    w('    let beta = fe_mul(&p.x, &gamma);')
    w('    // alpha = 3 (x - delta) (x + delta)')
    w('    let t = fe_mul(&fe_sub(&p.x, &delta), &fe_add(&p.x, &delta));')
    w('    let alpha = fe_add(&fe_add(&t, &t), &t);')
    w('    let beta2 = fe_add(&beta, &beta);')
    w('    let beta4 = fe_add(&beta2, &beta2);')
    w('    let x3 = fe_sub(&fe_sqr(&alpha), &fe_add(&beta4, &beta4));')
    w('    let z = fe_mul(&p.y, &p.z);')
    w('    let z3 = fe_add(&z, &z);')
    w('    let g2 = fe_sqr(&gamma);')
    w('    let g4 = fe_add(&g2, &g2);')
    w('    let g4 = fe_add(&g4, &g4);')
    w('    let g8 = fe_add(&g4, &g4);')
    w('    let y3 = fe_sub(&fe_mul(&alpha, &fe_sub(&beta4, &x3)), &g8);')
    w('    Point { x: x3, y: y3, z: z3 }')
    w('}')
    w('')
    w('// p1 + p2 (add-2007-bl, 12M + 4S) for p1, p2 not the identity, and 1 if')
    w('// they are equal (the sum is then wrong: double instead), else 0. p1 =')
    w('// -p2 gives the identity.')
    w('fn add_jac(p1: &Point, p2: &Point) -> (Point, u64) {')
    w('    let z1z1 = fe_sqr(&p1.z);')
    w('    let z2z2 = fe_sqr(&p2.z);')
    w('    let u1 = fe_mul(&p1.x, &z2z2);')
    w('    let u2 = fe_mul(&p2.x, &z1z1);')
    w('    let s1 = fe_mul(&p1.y, &fe_mul(&p2.z, &z2z2));')
    w('    let s2 = fe_mul(&p2.y, &fe_mul(&p1.z, &z1z1));')
    w('    let h = fe_sub(&u2, &u1);')
    w('    let r = fe_sub(&s2, &s1);')
    w('    let equal = fe_is_zero(&h) & fe_is_zero(&r);')
    w('    let hh = fe_sqr(&h);')
    w('    let hhh = fe_mul(&h, &hh);')
    w('    let v = fe_mul(&u1, &hh);')
    w('    let x3 = fe_sub(&fe_sub(&fe_sqr(&r), &hhh), &fe_add(&v, &v));')
    w('    let y3 = fe_sub(&fe_mul(&r, &fe_sub(&v, &x3)), &fe_mul(&s1, &hhh));')
    w('    let z3 = fe_mul(&fe_mul(&p1.z, &p2.z), &h);')
    w('    (Point { x: x3, y: y3, z: z3 }, equal)')
    w('}')
    w('')
    w('// p1 + (x2, y2) (madd, 8M + 3S) for p1 not the identity and not equal to')
    w('// (x2, y2).')
    w('fn add_affine(p1: &Point, x2: &Fe, y2: &Fe) -> Point {')
    w('    let z1z1 = fe_sqr(&p1.z);')
    w('    let u2 = fe_mul(x2, &z1z1);')
    w('    let s2 = fe_mul(y2, &fe_mul(&p1.z, &z1z1));')
    w('    let h = fe_sub(&u2, &p1.x);')
    w('    let r = fe_sub(&s2, &p1.y);')
    w('    let hh = fe_sqr(&h);')
    w('    let hhh = fe_mul(&h, &hh);')
    w('    let v = fe_mul(&p1.x, &hh);')
    w('    let x3 = fe_sub(&fe_sub(&fe_sqr(&r), &hhh), &fe_add(&v, &v));')
    w('    let y3 = fe_sub(&fe_mul(&r, &fe_sub(&v, &x3)), &fe_mul(&p1.y, &hhh));')
    w('    let z3 = fe_mul(&p1.z, &h);')
    w('    Point { x: x3, y: y3, z: z3 }')
    w('}')
    w('')
    w('// c ? a : b (c is 0 or 1), in constant time.')
    w('fn point_select(c: u64, a: &Point, b: &Point) -> Point {')
    w('    Point { x: fe_select(c, &a.x, &b.x), y: fe_select(c, &a.y, &b.y), z: fe_select(c, &a.z, &b.z) }')
    w('}')
    w('')
    w('// 1 if p is the identity, else 0.')
    w('fn is_identity(p: &Point) -> u64 { fe_is_zero(&p.z) }')
    w('')
    w("// p1 + p2 for any points (Go's P256Point.Add): the doubling when they are")
    w('// equal, the other when one is the identity; constant time.')
    w('fn add(p1: &Point, p2: &Point) -> Point {')
    w('    let (sum, equal) = add_jac(p1, p2);')
    w('    let dbl = double(p1);')
    w('    let s = point_select(equal, &dbl, &sum);')
    w('    let s = point_select(is_identity(p2), p1, &s);')
    w('    point_select(is_identity(p1), p2, &s)')
    w('}')
    w('')
    asm = c.get('asm', [])
    if asm:
        arches = ', '.join(f'target_arch = "{a}"' for a in asm)
        w(f'// table[idx] (idx < table.len()), every entry read. In assembly on {", ".join(asm)}')
        w(f'// (nistec_{key}_<arch>.s).')
        w(f'#[cfg(any({arches}))]')
        w('#[asm]')
        w('fn select_point(table: *const Point, n: usize, idx: u64) -> Point;')
        w('')
        w(f'#[cfg(any({arches}))]')
        w('fn lookup(table: &[Point], idx: u64) -> Point { select_point(table.as_ptr(), table.len(), idx) }')
        w('')
        w(f'#[cfg(not(any({arches})))]')
    else:
        w('// table[idx] (idx < table.len()), every entry read.')
    w('fn lookup(table: &[Point], idx: u64) -> Point {')
    w('    let mut r = identity();')
    w('    r.y = ZERO;')
    w('    let mut j = 0;')
    w('    while j < table.len() {')
    w('        let d = (j as u64) ^ idx;')
    w('        let eq = ((d | d.wrapping_neg()) >> 63) ^ 1;')
    w('        let t = &table[j];')
    w('        r.x = fe_select(eq, &t.x, &r.x);')
    w('        r.y = fe_select(eq, &t.y, &r.y);')
    w('        r.z = fe_select(eq, &t.z, &r.z);')
    w('        j += 1;')
    w('    }')
    w('    r')
    w('}')
    w('')
    w("// Booth's signed recoding of a 6-bit window (Go's boothW5): (|digit|,")
    w('// 1 if negative), the digit in [-16, 16].')
    w('fn booth5(w: u64) -> (u64, u64) {')
    w('    let s = !((w >> 5).wrapping_sub(1));')
    w('    let mut d = (1u64 << 6).wrapping_sub(w).wrapping_sub(1);')
    w('    d = (d & s) | (w & !s);')
    w('    d = (d >> 1) + (d & 1);')
    w('    (d, s & 1)')
    w('}')
    w('')
    w('// Bits index .. index + 5 of the limbs (zero above them).')
    w('fn window6(k: &Fe, index: usize) -> u64 {')
    w('    let i = index / 64;')
    w('    let sh = index % 64;')
    w('    let mut w = k[i] >> sh as u64;')
    w('    if sh > 58 && i + 1 < LIMBS { w = w | (k[i + 1] << (64 - sh) as u64); }')
    w('    w & 0x3f')
    w('}')
    w('')
    w("// k * p (k big-endian, below n), in constant time: Go's p256ScalarMult,")
    w('// signed 5-bit windows over a table of p, 2p, ..., 16p.')
    w('fn scalar_mult(p: &Point, k: &[u8]) -> Point {')
    w('    let (kl, _) = sc_limbs(k);')
    w('    let kl = sc_reduce(&kl);')
    w('    let mut table: Vec<Point> = Vec::with_capacity(16);')
    w('    table.push(p.clone());')
    w('    table.push(double(p));')
    w('    let mut i = 2;')
    w('    while i < 16 {')
    w('        let t = if i % 2 == 1 { double(&table[i / 2]) } else { add_jac(&table[i - 1], p).0 };')
    w('        table.push(t);')
    w('        i += 1;')
    w('    }')
    w('    // Entry sel - 1 for the digit sel in 1..16 (0: none, all zero).')
    w('    let mut index = TOP_WINDOW;')
    w('    let (sel0, _) = booth5(window6(&kl, index));')
    w('    let mut q = lookup(table.as_slice(), sel0.wrapping_sub(1));')
    w('    let mut zero = sel0;')
    w('    while index > 4 {')
    w('        index -= 5;')
    w('        q = double(&double(&double(&double(&double(&q)))));')
    w('        let (sel, sign) = booth5(window6(&kl, index));')
    w('        let mut t0 = lookup(table.as_slice(), sel.wrapping_sub(1));')
    w('        t0.y = fe_select(sign, &fe_sub(&ZERO, &t0.y), &t0.y);')
    w('        let (sum, _) = add_jac(&q, &t0);')
    w('        let t1 = point_select(nonzero(sel), &sum, &q);')
    w('        q = point_select(nonzero(zero), &t1, &t0);')
    w('        zero = zero | sel;')
    w('    }')
    w('    q = double(&double(&double(&double(&double(&q)))));')
    w('    let (sel, sign) = booth5((kl[0] << 1) & 0x3f);')
    w('    let mut t0 = lookup(table.as_slice(), sel.wrapping_sub(1));')
    w('    t0.y = fe_select(sign, &fe_sub(&ZERO, &t0.y), &t0.y);')
    w('    let (sum, _) = add_jac(&q, &t0);')
    w('    let t1 = point_select(nonzero(sel), &sum, &q);')
    w('    q = point_select(nonzero(zero), &t1, &t0);')
    w('    // The identity (all zero above) as (1, 1, 0).')
    w('    point_select(nonzero(zero | sel), &q, &identity())')
    w('}')
    w('')
    w('// 1 if x is not 0, else 0.')
    w('fn nonzero(x: u64) -> u64 { (x | x.wrapping_neg()) >> 63 }')
    w('')
    w('// An affine point (x, y), Montgomery form, never the identity.')
    w('#[derive(Clone)]')
    w('struct Affine {')
    w('    x: Fe,')
    w('    y: Fe,')
    w('}')
    w('')
    w("// The generator's multiples as affine points: for window w (of 2 * SIZE,")
    w('// least significant first), j * 16^w * G (j in 1..16) at 15 * w + j - 1.')
    w('// Computed in Jacobian coordinates, then made affine with one inversion')
    w("// (Montgomery's trick).")
    w('static BASE: LazyLock<Vec<Affine>> = LazyLock::new(base_table);')
    w('')
    w('fn base_table() -> Vec<Affine> {')
    w('    let mut pts: Vec<Point> = Vec::with_capacity(30 * SIZE);')
    w('    let mut g = generator();')
    w('    let mut wi = 0;')
    w('    while wi < 2 * SIZE {')
    w('        let mut acc = g.clone();')
    w('        let mut j = 1;')
    w('        while j < 16 {')
    w('            pts.push(acc.clone());')
    w('            if j < 15 { acc = add(&acc, &g); }')
    w('            j += 1;')
    w('        }')
    w('        g = double(&double(&double(&double(&g))));')
    w('        wi += 1;')
    w('    }')
    w('    // prefix[i] = z0 * ... * zi; then each 1/zi from 1/prefix.')
    w('    let mut prefix: Vec<Fe> = Vec::with_capacity(pts.len());')
    w('    let mut acc = ONE;')
    w('    for p in pts.iter() {')
    w('        acc = fe_mul(&acc, &p.z);')
    w('        prefix.push(acc);')
    w('    }')
    w('    let mut inv = fe_inv(&acc);')
    w('    let mut out: Vec<Affine> = Vec::with_capacity(pts.len());')
    w('    out.resize(pts.len(), Affine { x: ZERO, y: ZERO });')
    w('    let mut i = pts.len();')
    w('    while i > 0 {')
    w('        i -= 1;')
    w('        let zi = if i > 0 { fe_mul(&inv, &prefix[i - 1]) } else { inv };')
    w('        inv = fe_mul(&inv, &pts[i].z);')
    w('        let zi2 = fe_sqr(&zi);')
    w('        out[i] = Affine { x: fe_mul(&pts[i].x, &zi2), y: fe_mul(&pts[i].y, &fe_mul(&zi2, &zi)) };')
    w('    }')
    w('    out')
    w('}')
    w('')
    w('// table[idx] (idx < 15 or none: zero), every entry read.')
    w('fn lookup_affine(table: &[Affine], idx: u64) -> Affine {')
    w('    let mut r = Affine { x: ZERO, y: ZERO };')
    w('    let mut j = 0;')
    w('    while j < table.len() {')
    w('        let d = (j as u64) ^ idx;')
    w('        let eq = ((d | d.wrapping_neg()) >> 63) ^ 1;')
    w('        r.x = fe_select(eq, &table[j].x, &r.x);')
    w('        r.y = fe_select(eq, &table[j].y, &r.y);')
    w('        j += 1;')
    w('    }')
    w('    r')
    w('}')
    w('')
    w('// k * G (k big-endian, SIZE bytes or fewer), in constant time: a lookup and')
    w("// a mixed addition per 4-bit window, no doubling (as Go's p256BaseMult with")
    w('// its affine tables).')
    w('fn scalar_base_mult(k: &[u8]) -> Point {')
    w('    let t = LazyLock::force(&BASE);')
    w('    let mut q = identity();')
    w('    let mut zero = 0u64;')
    w('    let mut wi = 0;')
    w('    let mut i = k.len();')
    w('    while i > 0 && wi < 2 * SIZE {')
    w('        i -= 1;')
    w('        let mut h = 0;')
    w('        while h < 2 {')
    w('            let nib = if h == 0 { (k[i] & 15) as u64 } else { (k[i] >> 4) as u64 };')
    w('            let e = lookup_affine(&t[15 * wi..15 * wi + 15], nib.wrapping_sub(1));')
    w('            let sum = add_affine(&q, &e.x, &e.y);')
    w('            let r = point_select(nonzero(nib), &sum, &q);')
    w('            q = point_select(nonzero(zero), &r, &Point { x: e.x, y: e.y, z: ONE });')
    w('            zero = zero | nib;')
    w('            wi += 1;')
    w('            h += 1;')
    w('        }')
    w('    }')
    w('    point_select(nonzero(zero), &q, &identity())')
    w('}')
    w('')
    w('// (x, y) of p (Montgomery form); None for the identity.')
    w('fn affine(p: &Point) -> Option<(Fe, Fe)> {')
    w('    if fe_is_zero(&p.z) == 1 { return None; }')
    w('    let zi = fe_inv(&p.z);')
    w('    let zi2 = fe_sqr(&zi);')
    w('    Some((fe_mul(&p.x, &zi2), fe_mul(&p.y, &fe_mul(&zi2, &zi))))')
    w('}')
    w('')
    w('// x^3 - 3x + b.')
    w('fn rhs(x: &Fe) -> Fe {')
    w('    let x3 = fe_mul(&fe_sqr(x), x);')
    w('    let three_x = fe_add(&fe_add(x, x), x);')
    w('    fe_add(&fe_sub(&x3, &three_x), &B)')
    w('}')
    w('')
    w('// The point of a SEC 1 encoding (uncompressed or compressed), if on the')
    w('// curve.')
    w('fn decode(b: &[u8]) -> Option<Point> {')
    w('    if b.len() == 1 + 2 * SIZE && b[0] == 4 {')
    w('        let x = fe_from_be(&b[1..1 + SIZE])?;')
    w('        let y = fe_from_be(&b[1 + SIZE..])?;')
    w('        if !fe_eq(&fe_sqr(&y), &rhs(&x)) { return None; }')
    w('        return Some(Point { x, y, z: ONE });')
    w('    }')
    w('    if b.len() == 1 + SIZE && (b[0] == 2 || b[0] == 3) {')
    w('        let x = fe_from_be(&b[1..])?;')
    w('        let r = rhs(&x);')
    w('        let mut y = fe_pow(&r, &SQRT_EXP);')
    w('        if !fe_eq(&fe_sqr(&y), &r) { return None; }')
    w('        let odd = fe_to_be(&y)[SIZE - 1] & 1;')
    w('        if odd != (b[0] & 1) { y = fe_sub(&ZERO, &y); }')
    w('        return Some(Point { x, y, z: ONE });')
    w('    }')
    w('    None')
    w('}')
    w('')
    w('// The uncompressed SEC 1 encoding (empty for the identity).')
    w('fn encode(p: &Point) -> Vec<u8> {')
    w('    let mut out: Vec<u8> = Vec::new();')
    w('    if let Some((x, y)) = affine(p) {')
    w('        out.reserve(1 + 2 * SIZE);')
    w('        out.push(4);')
    w('        out.extend_from_slice(fe_to_be(&x).as_slice());')
    w('        out.extend_from_slice(fe_to_be(&y).as_slice());')
    w('    }')
    w('    out')
    w('}')
    w('')
    w('// --- For crypto::ec (bytes in, bytes out) ---')
    w('')
    w('/// The uncompressed encoding of a SEC 1 point, if valid.')
    w('pub(crate) fn decode_point(b: &[u8]) -> Option<Vec<u8>> {')
    w('    let p = decode(b)?;')
    w('    Some(encode(&p))')
    w('}')
    w('')
    w('/// k * G, uncompressed (empty for the identity).')
    w('pub(crate) fn base_mult(k: &[u8]) -> Vec<u8> { encode(&scalar_base_mult(k)) }')
    w('')
    w('/// The x-coordinate of k * peer (a valid uncompressed point), if not the')
    w('/// identity.')
    w('pub(crate) fn ecdh(k: &[u8], peer: &[u8]) -> Option<Vec<u8>> {')
    w('    let p = decode(peer)?;')
    w('    let (x, _) = affine(&scalar_mult(&p, k))?;')
    w('    Some(fe_to_be(&x))')
    w('}')
    w('')
    w('/// The x-coordinate of u1 * G + u2 * q (q a valid uncompressed point), if')
    w('/// not the identity.')
    w('pub(crate) fn mul2_x(u1: &[u8], u2: &[u8], q: &[u8]) -> Option<Vec<u8>> {')
    w('    let qp = decode(q)?;')
    w('    let r = add(&scalar_base_mult(u1), &scalar_mult(&qp, u2));')
    w('    let (x, _) = affine(&r)?;')
    w('    Some(fe_to_be(&x))')
    w('}')
    return '\n'.join(out) + '\n'


def scalar_code(c):
    # Arithmetic modulo the group order n, for ECDSA: the field code with
    # n for p (prefix sc_).
    q, n = c['n'], c['limbs']
    size = (q.bit_length() + 7) // 8
    R = 1 << (64 * n)
    m0inv = (-pow(q, -1, 1 << 64)) % (1 << 64)
    out = []
    w = out.append
    w('')
    w('// --- Scalars: modulo the group order N (Montgomery form) ---')
    w('')
    w(f'const N: Fe = {arr(q, n)};')
    w(f'const N_ONE: Fe = {arr(R % q, n)};')
    w(f'const N_RR: Fe = {arr(R * R % q, n)};')
    w(f'const N_MINUS_2: [u8; {size}] = {be_bytes(q - 2, size)};')
    w('')
    w('fn sc_mul(a: &Fe, b: &Fe) -> Fe {')
    for i in range(n + 2):
        w(f'    let mut t{i} = 0u64;')
    w('    let mut c: u64;')
    for i in range(n):
        w(f'    let bi = b[{i}];')
        w('    c = 0;')
        for j in range(n):
            w(f'    let (x, y) = mac(a[{j}], bi, t{j}, c); t{j} = x; c = y;')
        w(f'    let (x, y) = adc(t{n}, c, false); t{n} = x; t{n + 1} = y as u64;')
        w(f'    let q = t0.wrapping_mul({m0inv:#x});')
        w(f'    let (_, y) = mac(q, N[0], t0, 0); c = y;')
        for j in range(1, n):
            w(f'    let (x, y) = mac(q, N[{j}], t{j}, c); t{j - 1} = x; c = y;')
        w(f'    let (x, y) = adc(t{n}, c, false); t{n - 1} = x; t{n} = t{n + 1}.wrapping_add(y as u64);')
    w('    let (r0, w0) = sbb(t0, N[0], false);')
    for j in range(1, n):
        w(f'    let (r{j}, w{j}) = sbb(t{j}, N[{j}], w{j - 1});')
    w(f'    let (_, bb) = sbb(t{n}, 0, w{n - 1});')
    w('    let mask = 0u64.wrapping_sub(bb as u64);')
    w('    [' + ', '.join(f'(t{j} & mask) | (r{j} & !mask)' for j in range(n)) + ']')
    w('}')
    w('')
    w('fn sc_add(a: &Fe, b: &Fe) -> Fe {')
    w('    let (s0, c0) = adc(a[0], b[0], false);')
    for j in range(1, n):
        w(f'    let (s{j}, c{j}) = adc(a[{j}], b[{j}], c{j - 1});')
    w('    let (d0, w0) = sbb(s0, N[0], false);')
    for j in range(1, n):
        w(f'    let (d{j}, w{j}) = sbb(s{j}, N[{j}], w{j - 1});')
    w(f'    let (_, keep) = sbb(c{n - 1} as u64, 0, w{n - 1});')
    w('    let mask = 0u64.wrapping_sub(keep as u64);')
    w('    [' + ', '.join(f'(s{j} & mask) | (d{j} & !mask)' for j in range(n)) + ']')
    w('}')
    w('')
    w('// a^(n-2): 1/a (a in Montgomery form; the exponent is public).')
    w('fn sc_inv(a: &Fe) -> Fe {')
    w('    let mut r = N_ONE;')
    w('    for byte in N_MINUS_2.iter() {')
    w('        let mut k = 8;')
    w('        while k > 0 {')
    w('            k -= 1;')
    w('            r = sc_mul(&r, &r);')
    w('            if ((*byte >> k as u8) & 1) != 0 { r = sc_mul(&r, a); }')
    w('        }')
    w('    }')
    w('    r')
    w('}')
    w('')
    w('// Big-endian bytes (SIZE or fewer) as limbs, and whether below n.')
    w('fn sc_limbs(b: &[u8]) -> (Fe, bool) {')
    w('    let mut x: Fe = ZERO;')
    w('    let mut i = 0;')
    w('    while i < b.len() && i < SIZE {')
    w('        let k = b.len() - 1 - i;')
    w('        x[i / 8] = x[i / 8] | ((b[k] as u64) << (8 * (i % 8)) as u64);')
    w('        i += 1;')
    w('    }')
    w('    let (_, w0) = sbb(x[0], N[0], false);')
    for j in range(1, n):
        w(f'    let (_, w{j}) = sbb(x[{j}], N[{j}], w{j - 1});')
    w(f'    (x, w{n - 1})')
    w('}')
    w('')
    w('// x - n if x >= n (x < 2n), in constant time.')
    w('fn sc_reduce(x: &Fe) -> Fe {')
    w('    let (d0, w0) = sbb(x[0], N[0], false);')
    for j in range(1, n):
        w(f'    let (d{j}, w{j}) = sbb(x[{j}], N[{j}], w{j - 1});')
    w(f'    let mask = 0u64.wrapping_sub(w{n - 1} as u64);')
    w('    [' + ', '.join(f'(x[{j}] & mask) | (d{j} & !mask)' for j in range(n)) + ']')
    w('}')
    w('')
    w('fn sc_to_mont(x: &Fe) -> Fe { sc_mul(x, &N_RR) }')
    w('')
    w('fn sc_from_mont(x: &Fe) -> Fe {')
    w('    let mut one: Fe = ZERO;')
    w('    one[0] = 1;')
    w('    sc_mul(x, &one)')
    w('}')
    w('')
    w('fn limbs_to_be(x: &Fe) -> Vec<u8> {')
    w('    let mut out: Vec<u8> = Vec::with_capacity(SIZE);')
    w('    let mut k = SIZE;')
    w('    while k > 0 {')
    w('        k -= 1;')
    w('        out.push((x[k / 8] >> (8 * (k % 8)) as u64) as u8);')
    w('    }')
    w('    out')
    w('}')
    w('')
    w('// The hash as a scalar: its leftmost SIZE bytes, mod n (n has whole')
    w('// bytes for these curves).')
    w('fn hash_scalar(hash: &[u8]) -> Fe {')
    w('    let e = if hash.len() > SIZE { &hash[..SIZE] } else { hash };')
    w('    let (x, _) = sc_limbs(e);')
    w('    sc_reduce(&x)')
    w('}')
    w('')
    w('/// An ECDSA signature (r, s) of hash by the secret scalar d with the')
    w('/// nonce k (both in [1, n), big-endian); None if r or s is zero (pick')
    w('/// another nonce). Constant-time in d and k.')
    w('pub(crate) fn sign(d: &[u8], k: &[u8], hash: &[u8]) -> Option<(Vec<u8>, Vec<u8>)> {')
    w('    let (rx, _) = affine(&scalar_base_mult(k))?;')
    w('    let (xl, _) = sc_limbs(fe_to_be(&rx).as_slice());')
    w('    let r = sc_reduce(&xl);')
    w('    if fe_is_zero(&r) == 1 { return None; }')
    w('    let (kl, _) = sc_limbs(k);')
    w('    let (dl, _) = sc_limbs(d);')
    w('    let e = sc_to_mont(&hash_scalar(hash));')
    w('    let kinv = sc_inv(&sc_to_mont(&kl));')
    w('    // s = (e + r d) / k')
    w('    let rd = sc_mul(&sc_to_mont(&r), &sc_to_mont(&dl));')
    w('    let s = sc_from_mont(&sc_mul(&kinv, &sc_add(&e, &rd)));')
    w('    if fe_is_zero(&s) == 1 { return None; }')
    w('    Some((limbs_to_be(&r), limbs_to_be(&s)))')
    w('}')
    w('')
    w('/// Whether (r, s) is an ECDSA signature of hash by q (uncompressed).')
    w('pub(crate) fn verify(q: &[u8], hash: &[u8], r: &[u8], s: &[u8]) -> bool {')
    w('    if r.len() > SIZE || s.len() > SIZE { return false; }')
    w('    let (rl, r_ok) = sc_limbs(r);')
    w('    let (sl, s_ok) = sc_limbs(s);')
    w('    if !r_ok || !s_ok || fe_is_zero(&rl) == 1 || fe_is_zero(&sl) == 1 { return false; }')
    w('    let e = sc_to_mont(&hash_scalar(hash));')
    w('    let w = sc_inv(&sc_to_mont(&sl));')
    w('    let u1 = sc_from_mont(&sc_mul(&e, &w));')
    w('    let u2 = sc_from_mont(&sc_mul(&sc_to_mont(&rl), &w));')
    w('    let x = match mul2_x(limbs_to_be(&u1).as_slice(), limbs_to_be(&u2).as_slice(), q) {')
    w('        Some(x) => x,')
    w('        None => return false,')
    w('    };')
    w('    let (xl, _) = sc_limbs(x.as_slice());')
    w('    let xr = sc_reduce(&xl);')
    w('    let d = ' + ' | '.join(f'(xr[{j}] ^ rl[{j}])' for j in range(n)) + ';')
    w('    d == 0')
    w('}')
    return '\n'.join(out) + '\n'


